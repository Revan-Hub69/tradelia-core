'use client'

import { useTranslations } from 'next-intl'
import { DashboardLayout } from '@/src/widgets/dashboard-layout'
import { DashboardAuthGuard } from '@/src/widgets/dashboard-auth'
import { ComplexityIndicator } from '@/src/shared/ui/ComplexityIndicator'
import { CRYPTO_SECTIONS, type SectionId } from '@/src/shared/config/crypto-sections'

interface SectionDashboardProps {
  sectionId: SectionId
}

export function SectionDashboard({ sectionId }: SectionDashboardProps) {
  const t = useTranslations('sections')
  const section = CRYPTO_SECTIONS[sectionId]

  // Color mapping
  const colorClasses = {
    success: { bg: 'bg-success/10', text: 'text-success' },
    warning: { bg: 'bg-warning/10', text: 'text-warning' },
    error: { bg: 'bg-error/10', text: 'text-error' },
    info: { bg: 'bg-primary/10', text: 'text-primary' }
  }
  const colors = colorClasses[section.color] || colorClasses.success

  return (
    <DashboardAuthGuard>
      <DashboardLayout>
        {/* Page Header */}
        <div className="mb-8">
          <div className="flex items-start gap-4">
            <div className={`w-12 h-12 rounded-xl ${colors.bg} flex items-center justify-center flex-shrink-0`}>
              <SectionIcon type={section.icon} className={`w-6 h-6 ${colors.text}`} />
            </div>
            <div className="flex-1">
              <h1 className="text-2xl sm:text-3xl font-bold text-foreground mb-1">
                {t(`${sectionId}.title`)}
              </h1>
              <p className="text-muted-foreground">
                {t(`${sectionId}.subtitle`)}
              </p>
              <div className="flex items-center gap-3 mt-3">
                <ComplexityIndicator level={section.complexity} size="sm" />
                <span className="text-sm text-muted-foreground">
                  {t(`${sectionId}.complexity`)}
                </span>
              </div>
            </div>
          </div>
        </div>

        {/* Main Content */}
        <div className="space-y-8 pb-8">
          {/* What it analyzes */}
          <section className="section-frame p-6">
            <h2 className="text-lg font-semibold text-foreground mb-4">
              {t(`${sectionId}.whatItAnalyzes`)}
            </h2>
            <ul className="space-y-3">
              {[0, 1, 2].map((index) => (
                <li key={index} className="flex items-start gap-3">
                  <div className={`w-6 h-6 rounded-full ${colors.bg} ${colors.text} flex items-center justify-center flex-shrink-0 text-sm font-medium`}>
                    {index + 1}
                  </div>
                  <span className="text-muted-foreground">
                    {t(`${sectionId}.whatItAnalyzesList.${index}`)}
                  </span>
                </li>
              ))}
            </ul>
          </section>

          {/* Focus Areas */}
          <section className="section-frame p-6">
            <h2 className="text-lg font-semibold text-foreground mb-4">
              {t('ui.focus')}
            </h2>
            <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
              {section.focusAreas.map((focus) => (
                <div 
                  key={focus.id}
                  className="p-4 rounded-lg bg-muted/30 border border-border/50"
                >
                  <div className={`w-8 h-8 rounded-lg ${colors.bg} flex items-center justify-center mb-3`}>
                    <FocusIcon sectionId={sectionId} focusId={focus.id} className={`w-4 h-4 ${colors.text}`} />
                  </div>
                  <h3 className="font-medium text-foreground">
                    {t(`${sectionId}.focus.${focus.id}`)}
                  </h3>
                </div>
              ))}
            </div>
          </section>

          {/* Coming Soon - Modules */}
          <section className="section-frame p-6 border-dashed">
            <div className="text-center py-8">
              <div className="w-16 h-16 rounded-full bg-muted/50 flex items-center justify-center mx-auto mb-4">
                <BookIcon className="w-8 h-8 text-muted-foreground" />
              </div>
              <h3 className="text-lg font-semibold text-foreground mb-2">
                Moduli educativi in arrivo
              </h3>
              <p className="text-sm text-muted-foreground max-w-md mx-auto">
                {t(`${sectionId}.description`)}
              </p>
            </div>
          </section>
        </div>
      </DashboardLayout>
    </DashboardAuthGuard>
  )
}

